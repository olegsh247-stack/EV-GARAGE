CREATE TABLE brands (
  slug        TEXT PRIMARY KEY,
  name        TEXT NOT NULL,
  country     TEXT NOT NULL DEFAULT 'China',
  description TEXT NOT NULL DEFAULT '',
  accent      TEXT NOT NULL DEFAULT '#0EA5A0',
  logo        TEXT NOT NULL DEFAULT '',
  sort_order  INTEGER NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE models (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_slug  TEXT NOT NULL REFERENCES brands(slug) ON DELETE CASCADE,
  slug        TEXT NOT NULL,
  name        TEXT NOT NULL,
  tagline     TEXT NOT NULL DEFAULT '',
  body_type   TEXT NOT NULL DEFAULT '',
  seats       INTEGER NOT NULL DEFAULT 5,
  description TEXT NOT NULL DEFAULT '',
  archived    BOOLEAN NOT NULL DEFAULT false,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (brand_slug, slug)
);

CREATE INDEX idx_models_brand ON models(brand_slug);
CREATE INDEX idx_models_archived ON models(archived);

CREATE TABLE model_colors (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_slug  TEXT NOT NULL,
  model_slug  TEXT NOT NULL,
  kind        TEXT NOT NULL CHECK (kind IN ('exterior', 'interior')),
  name        TEXT NOT NULL,
  hex         TEXT NOT NULL,
  sort_order  INTEGER NOT NULL DEFAULT 0,
  FOREIGN KEY (brand_slug, model_slug)
    REFERENCES models(brand_slug, slug) ON DELETE CASCADE
);

CREATE TABLE trims (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_slug      TEXT NOT NULL,
  model_slug      TEXT NOT NULL,
  slug            TEXT NOT NULL,
  name            TEXT NOT NULL,
  highlight       TEXT,
  price_from      INTEGER NOT NULL,
  price_cny       INTEGER,
  powertrain_type TEXT NOT NULL CHECK (powertrain_type IN ('BEV', 'EREV', 'PHEV', 'HEV')),
  motor_model     TEXT,
  range_km        INTEGER NOT NULL,
  total_range_km  INTEGER NOT NULL,
  power_hp        INTEGER NOT NULL,
  power_kw        INTEGER NOT NULL,
  power_p30_kw    DOUBLE PRECISION,
  ice_power_kw    DOUBLE PRECISION,
  ice_power_hp    INTEGER,
  lidar           TEXT,
  torque_nm       INTEGER NOT NULL,
  accel_sec       DOUBLE PRECISION NOT NULL,
  top_speed_kmh   INTEGER NOT NULL,
  battery_kwh     DOUBLE PRECISION NOT NULL,
  battery_type    TEXT NOT NULL DEFAULT '',
  fast_charge     TEXT NOT NULL DEFAULT '',
  drive           TEXT NOT NULL DEFAULT '',
  length_mm       INTEGER,
  width_mm        INTEGER,
  height_mm       INTEGER,
  wheelbase_mm    INTEGER,
  front_track_mm  INTEGER,
  curb_weight_kg  INTEGER,
  gross_weight_kg INTEGER,
  turning_radius_m DOUBLE PRECISION,
  sort_order      INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (brand_slug, model_slug, slug),
  FOREIGN KEY (brand_slug, model_slug)
    REFERENCES models(brand_slug, slug) ON DELETE CASCADE
);

CREATE INDEX idx_trims_model ON trims(brand_slug, model_slug);

CREATE TABLE suggestions (
  id          TEXT PRIMARY KEY,
  type        TEXT NOT NULL CHECK (type IN ('new', 'archive')),
  title       TEXT NOT NULL,
  note        TEXT NOT NULL DEFAULT '',
  source_url  TEXT,
  brand_slug  TEXT,
  model_slug  TEXT,
  status      TEXT NOT NULL DEFAULT 'pending'
                CHECK (status IN ('pending', 'approved', 'rejected')),
  added_at    TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_suggestions_status ON suggestions(status);

CREATE TABLE contact (
  id             INTEGER PRIMARY KEY CHECK (id = 1),
  phone_display  TEXT NOT NULL,
  phone_href     TEXT NOT NULL,
  whatsapp_href  TEXT NOT NULL,
  telegram_href  TEXT NOT NULL,
  email          TEXT NOT NULL,
  updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE archived_models (
  brand_slug  TEXT NOT NULL,
  model_slug  TEXT NOT NULL,
  archived_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  note        TEXT,
  PRIMARY KEY (brand_slug, model_slug)
);

CREATE TABLE videos (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  youtube_id  TEXT NOT NULL,
  title       TEXT NOT NULL,
  channel     TEXT NOT NULL,
  brand_slug  TEXT NOT NULL,
  model_slug  TEXT NOT NULL,
  sort_order  INTEGER NOT NULL,
  UNIQUE (brand_slug, model_slug, youtube_id)
);

CREATE TABLE suggestion_statuses (
  suggestion_id TEXT PRIMARY KEY,
  status        TEXT NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE photos (
  photo_key     TEXT NOT NULL,
  photo_index   INTEGER NOT NULL CHECK (photo_index >= 0 AND photo_index < 25),
  sort_position INTEGER NOT NULL,
  object_key    TEXT NOT NULL UNIQUE,
  content_type  TEXT NOT NULL,
  ext           TEXT NOT NULL,
  byte_size     INTEGER NOT NULL CHECK (byte_size >= 0),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (photo_key, photo_index),
  UNIQUE (photo_key, sort_position)
);

CREATE INDEX idx_photos_order ON photos(photo_key, sort_position);
